#!/usr/bin/env python3
"""Build results/summary.md and figures from results/raw/*.csv. No hand-typed numbers."""
import glob, os, sys
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd, yaml
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "results"); RAW = os.path.join(RES, "raw")
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "lib"))
import pqsig.accounting as acc

L = []
def w(s=""): L.append(s)
def md(df): return df.to_markdown(index=False, floatfmt=".4g")

def load(name):
    p = os.path.join(RAW, name)
    return pd.read_csv(p) if os.path.exists(p) else None

timing = [pd.read_csv(f) for f in sorted(glob.glob(os.path.join(RAW, "*timing*.csv")))]
timing = pd.concat(timing, ignore_index=True) if timing else None
score = load("scoring.csv"); loss = load("lossmodel.csv")
prof = yaml.safe_load(open(os.path.join(HERE, "profiles.yaml")))
pq_present = timing is not None and (timing.family == "pq").any()

w("# benchmark: results summary (generated by experiments/summarize.py)")
w()
meta = pd.concat([d for d in (timing, score, loss) if d is not None])[["machine", "date", "git_commit"]].drop_duplicates()
w("Run tags (from CSV rows):"); w(); w(md(meta)); w()
w("**All runs are smoke tests (`machine: cloud-smoke`). No publication numbers.**")
w()
w("## Environment status")
w()
if pq_present:
    w("liboqs rows present in `raw/*timing*.csv`.")
else:
    w("**liboqs could not be built in the cloud session: github.com returned HTTP 403 via the proxy "
      "(host: github.com, path /open-quantum-safe/liboqs/archive/...). No PQ sizes or timings exist yet; "
      "Part A is classical-only here, Part B is scored for classical rows only, and every PQ cell is TODO-RESULT. "
      "No sizes were typed in from memory.**")
w()

# ---- Part A
w("## Part A: sign/verify/keygen timing and sizes")
w()
if timing is not None:
    w("Source: `results/raw/" + "`, `results/raw/".join(os.path.basename(f) for f in sorted(glob.glob(os.path.join(RAW, "*timing*.csv")))) + "`")
    w()
    a = timing[["scheme", "family", "backend", "iterations", "pk_bytes", "sig_bytes_max",
                "sign_mean_us", "sign_median_us", "sign_p95_us", "sign_p99_us",
                "verify_mean_us", "verify_median_us", "verify_p95_us", "verify_p99_us",
                "keygen_mean_us"]]
    w(md(a)); w()
    w("Classical rows use python-cryptography (OpenSSL), so they include Python call overhead; not comparable to the C liboqs rows.")
    w()

# ---- Q1
w("## Q1: which (scheme, mode) pairs fit each profile")
w()
w("Source: `results/raw/scoring.csv` (from `raw/*timing*.csv` sizes and `experiments/profiles.yaml`).")
w()
w("Profiles (`profiles.yaml`): " + "; ".join(f"{k}: {v['budget_bytes']} B budget, {v['frame_payload']} B frame ({v['source']})" for k, v in prof["profiles"].items()))
w()
w("Frame header for fragmentation is TODO-RESULT for cv2x, sib1, dns (frames use 0 header: lower bound). "
  "OSNMA budget is derived (16 x 104 bit); the 67/71 DSM-block reproduction from gap.md section 4 is TODO-RESULT (needs PQ sizes and the full text).")
w()
w("Byte-accounting formulas (from `lib/pqsig/accounting.py`):")
w(); w("```"); w(acc.__doc__.strip()); w("```"); w()
if score is not None:
    t = score[["scheme", "profile", "mode", "auth_bytes", "anchor_bytes", "share_of_budget", "frames", "fits"]]
    w(md(t)); w()
    if pq_present:
        fits = score[score.family == "pq"].groupby(["profile", "mode"]).fits.sum().reset_index(name="n_schemes_fit")
        w(md(fits)); w()
    fig, ax = plt.subplots(figsize=(8, 4))
    for (s, m), g in score.groupby(["scheme", "mode"]):
        ax.scatter(g.profile, g.share_of_budget, label=f"{s}/{m}", s=18)
    ax.axhline(1, color="k", ls="--"); ax.set_yscale("log"); ax.set_ylabel("auth bytes / budget")
    ax.legend(fontsize=5, ncol=2); fig.tight_layout(); fig.savefig(os.path.join(RES, "fig_q1_share.pdf")); plt.close(fig)
    w("Figure: `fig_q1_share.pdf` (source `raw/scoring.csv`).")
w()
w("**Verdict Q1: inconclusive (pending). Only classical rows can be scored; the question concerns PQ schemes.**" if not pq_present
  else "**Verdict Q1: see table; fits column is the evidence.**")
w()

# ---- Q2
w("## Q2: PQ-anchored chain vs fragmented signatures at 0-30% loss")
w()
w("Source: `results/raw/lossmodel.csv`. Seeded i.i.d. loss; 20 seeds x 5000 messages per cell; mean and std across seeds.")
w("Cited parameters: k=13 (FN-DSA) / 34 (ML-DSA) fragments, 324 B anchor (darzi2026a); signature 666 B / 2420 B (junquera2023assessment, Falcon-512 / Dilithium2 as in that note; "
  "NOT liboqs-measured). Assumed, not cited: r=2 carousel cycles, key delay d=2 slots, epoch 20 slots, 2 anchors/epoch, 16 B disclosed key, slot 160 ms (SIB1 period), deadline = r*k slots. "
  "Model: see `lib/pqsig/lossmodel.py` docstring. Results are sensitive to these assumptions.")
w()
verd = {}
if loss is not None:
    g = loss.groupby(["scenario", "scheme", "loss"])
    m = g[["share_verified", "bytes_per_verified", "p95_ms"]].agg(["mean", "std"])
    m.columns = ["_".join(c) for c in m.columns]
    m = m.reset_index()
    w(md(m)); w()
    fig, axs = plt.subplots(1, 3, figsize=(12, 3.5))
    for (scen, sch), gg in m.groupby(["scenario", "scheme"]):
        for ax, col in zip(axs, ("share_verified", "bytes_per_verified", "p95_ms")):
            ax.errorbar(gg.loss, gg[col + "_mean"], yerr=gg[col + "_std"], label=f"{scen}/{sch}", marker="o", ms=3, capsize=2)
            ax.set_xlabel("loss"); ax.set_ylabel(col)
    axs[1].set_yscale("log"); axs[0].legend(fontsize=6); fig.tight_layout()
    fig.savefig(os.path.join(RES, "fig_q2_loss.pdf")); plt.close(fig)
    w("Figure: `fig_q2_loss.pdf` (source `raw/lossmodel.csv`).")
    w()
    # per-metric verdicts: chain better at every loss>0 in every scenario with gap > 2 pooled std
    for col, better in (("share_verified", "higher"), ("bytes_per_verified", "lower"), ("p95_ms", "lower")):
        wins, tot = 0, 0
        for scen in m.scenario.unique():
            for lo in sorted(m.loss.unique()):
                if lo == 0: continue
                c = m[(m.scenario == scen) & (m.scheme == "chain") & (m.loss == lo)].iloc[0]
                f = m[(m.scenario == scen) & (m.scheme == "fragmented") & (m.loss == lo)].iloc[0]
                d = c[col + "_mean"] - f[col + "_mean"]
                if better == "lower": d = -d
                tot += 1; wins += d > 2 * max(c[col + "_std"], f[col + "_std"], 1e-12)
        verd[col] = (wins, tot)
    w("Cells where chain is better by more than 2 std (loss > 0, both scenarios):")
    w(); w(md(pd.DataFrame([{"metric": k, "chain_better_cells": a, "cells": b} for k, (a, b) in verd.items()]))); w()
    allw = all(a == b for a, b in verd.values()); none = all(a == 0 for a, b in verd.values())
    cnt = "; ".join(f"{k}: {a}/{b}" for k, (a, b) in verd.items())
    w("**Verdict Q2: " + ("supported" if allw else "refuted" if none else
      "inconclusive (mixed) under these smoke assumptions (" + cnt + " cells where chain is better by >2 std); chain is not better on every metric at every loss level") +
      "; PQ sizes are cited, not liboqs-measured.** p95 time is taken over verified messages only and is capped by the deadline, so a low verified share flatters the fragmented p95. "
      "The darzi2026a 10% point (~41 B vs ~1971 B retransmission overhead) uses a retransmission accounting that this carousel model does not reproduce; TODO-RESULT.")
w()

# ---- Q3
w("## Q3: size or timing tail binding (deadline miss from sign/verify tails)")
w()
w("Source: `results/raw/*timing*.csv` columns `*_frac_gt3ms`, `*_frac_gt100ms` (fraction of iterations over 3 ms / 100 ms), x86 only; MCU figures are cited from chhetri2026benchmarking, not measured.")
w()
if timing is not None:
    cols = ["scheme", "family", "sign_p99_us", "verify_p99_us", "sign_frac_gt3ms", "verify_frac_gt3ms", "sign_frac_gt100ms", "verify_frac_gt100ms"]
    w(md(timing[cols])); w()
w("**Verdict Q3: inconclusive (pending). Needs PQ rows (liboqs); classical rows alone cannot answer it.**" if not pq_present
  else "**Verdict Q3: derive from table above.**")
w()
w("## Runs still needed (on the user's machines, `experiments/run.sh`)")
w()
w("- Part A with liboqs at the pinned tag, all enabled signature schemes, 10000 iterations, on every target machine (set `MACHINE_NAME`).")
w("- Part B re-score on those sizes (`score.py` is run by `run.sh`); includes MAYO/UOV/SNOVA/CROSS if the liboqs build enables them (`-DOQS_ENABLE_SIG_STFL_*`/alg flags in `run.sh`).")
w("- Part C re-run with liboqs sizes substituted for the cited 666/2420 B, plus sensitivity sweep of r, d, E, a.")
w("- Baselines pending: darzi2026a 34/13 fragments and 324 B; junquera2023assessment 67/71 blocks (full text check); chen2025hybrid size tables vs liboqs; yoshizawa2026a (Bulletproofs); goertzen2022post.")
open(os.path.join(RES, "summary.md"), "w").write("\n".join(L) + "\n")
