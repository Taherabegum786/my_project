#!/usr/bin/env python3
"""Build results/summary.md and figures from results/raw/*.csv. No hand-typed numbers."""
import glob, os, sys
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd, yaml
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "results"); RAW = os.path.join(RES, "raw")
sys.path.insert(0, os.path.join(HERE, "..", "..", "..", "lib"))
import pqsig.accounting as acc

L = []
def w(s=""): L.append(s)
def md(df): return df.to_markdown(index=False, floatfmt=".4g")

def load(name):
    p = os.path.join(RAW, name)
    return pd.read_csv(p) if os.path.exists(p) else None

timing = [pd.read_csv(f) for f in sorted(glob.glob(os.path.join(RAW, "*timing*.csv")))]
timing = pd.concat(timing, ignore_index=True) if timing else None
score = load("scoring.csv"); loss = load("lossmodel.csv")
prof = yaml.safe_load(open(os.path.join(HERE, "profiles.yaml")))
def grp(n):
    for pre, g in (("ML-DSA", "ML-DSA"), ("Falcon", "Falcon/FN-DSA"), ("SLH_DSA", "SLH-DSA"), ("MAYO", "MAYO"), ("OV", "UOV"),
                   ("SNOVA", "SNOVA"), ("cross", "CROSS"), ("mqom", "MQOM"), ("Ed25519", "classical"), ("ECDSA", "classical")):
        if n.startswith(pre): return g
    return "other"
for _d in (timing, score):
    if _d is not None: _d["group"] = _d.scheme.map(grp)
pq_present = timing is not None and (timing.family == "pq").any()

w("# benchmark: results summary (generated by experiments/summarize.py)")
w()
meta = pd.concat([d for d in (timing, score, loss) if d is not None])[["machine", "date", "git_commit"]].drop_duplicates()
w("Run tags (from CSV rows):"); w(); w(md(meta)); w()
w("**All runs are smoke tests (`machine: cloud-smoke`). No publication numbers.**")
w()
w("## Environment status")
w()
if pq_present:
    w("liboqs rows present in `raw/*timing*.csv` (tag and scheme list in `experiments/ENV.md` and the `backend` column).")
else:
    w("**liboqs could not be built in the cloud session: github.com returned HTTP 403 via the proxy "
      "(host: github.com, path /open-quantum-safe/liboqs/archive/...). No PQ sizes or timings exist yet; "
      "Part A is classical-only here, Part B is scored for classical rows only, and every PQ cell is TODO-RESULT. "
      "No sizes were typed in from memory.**")
w()

# ---- Part A
w("## Part A: sign/verify/keygen timing and sizes")
w()
if timing is not None:
    w("Source: `results/raw/" + "`, `results/raw/".join(os.path.basename(f) for f in sorted(glob.glob(os.path.join(RAW, "*timing*.csv")))) + "`")
    w()
    cols = ["scheme", "family", "backend", "iterations", "pk_bytes", "sig_bytes_max",
            "sign_mean_us", "sign_median_us", "sign_p95_us", "sign_p99_us", "verify_mean_us", "verify_median_us",
            "verify_p95_us", "verify_p99_us", "keygen_mean_us"]
    n_slh = int((timing.group == "SLH-DSA").sum()); n_pq = int((timing.family == "pq").sum())
    w(f"{n_pq} liboqs (PQ) parameter sets plus {int((timing.family == 'classical').sum())} classical rows. All rows except the {n_slh} SLH-DSA parameter sets are listed below (the SLH-DSA rows are in the CSV and aggregated below). "
      "**Rows with iterations < 100 (slow schemes: CROSS, MQOM, SLH-DSA) have p95/p99 = near-maximum of very few samples; they are not tail estimates.**")
    w()
    w(md(timing[timing.group != "SLH-DSA"][cols])); w()
    agg = timing.groupby("group").agg(n_schemes=("scheme", "count"), sig_min=("sig_bytes_max", "min"), sig_max=("sig_bytes_max", "max"),
                                      sign_median_us_min=("sign_median_us", "min"), sign_median_us_max=("sign_median_us", "max"),
                                      verify_median_us_max=("verify_median_us", "max")).reset_index()
    w("Aggregate by family (all rows):"); w(); w(md(agg)); w()
    w("Classical rows use python-cryptography (OpenSSL), so they include Python call overhead; not comparable to the C liboqs rows.")
    w()

# ---- Q1
w("## Q1: which (scheme, mode) pairs fit each profile")
w()
w("Source: `results/raw/scoring.csv` (from `raw/*timing*.csv` sizes and `experiments/profiles.yaml`).")
w()
w("Profiles (`profiles.yaml`): " + "; ".join(f"{k}: {v['budget_bytes']} B budget, {v['frame_payload']} B frame ({v['source']})" for k, v in prof["profiles"].items()))
w()
w("Frame header for fragmentation is TODO-RESULT for cv2x, sib1, dns (frames use 0 header: lower bound). "
  "OSNMA budget is derived (16 x 104 bit); the 67/71 DSM-block reproduction from gap.md section 4 is TODO-RESULT (needs PQ sizes and the full text).")
w()
w("Byte-accounting formulas (from `lib/pqsig/accounting.py`):")
w(); w("```"); w(acc.__doc__.strip()); w("```"); w()
if score is not None:
    hy = score[(score["mode"] == "hybrid")].iloc[0]
    hyb_partner = hy.auth_bytes - hy.sig_bytes
    cd = acc.CHAIN_DEFAULTS
    w(f"Hybrid partner: Ed25519 ({int(hyb_partner)} B signature, taken from the `Ed25519` row of the sizes CSV by `score.py`); hybrid auth = {int(hyb_partner)} B + PQ signature, no public key or certificate counted.")
    w(f"Chain parameters in Q1 scoring (`lib/pqsig/accounting.py` CHAIN_DEFAULTS): tag {cd['tag']} B (darzi2026a), disclosed key {cd['key']} B, commitment {cd['commit']} B, timestamp {cd['ts']} B (last three assumed, not cited). "
      f"Steady-state auth = {cd['tag']+cd['key']} B per message; anchor = PQ signature + {cd['commit']+cd['ts']} B, sent once per epoch and required to fit in one budget for `fits`.")
    pqs = score[score.family == "pq"]
    w(f"Counts: {pqs.scheme.nunique()} PQ schemes x {score.profile.nunique()} profiles = {int((pqs['mode']=='full').sum())} (scheme, profile) pairs per mode; hybrid rows exist for {int((pqs['mode']=='hybrid').sum())} pairs; the scoring CSV also holds {int((score.family=='classical').sum())} classical rows, which are excluded from the pair totals below.")
    w()
if score is not None:
    w("Full per-(scheme, mode, profile) table: `raw/scoring.csv` (not repeated here). Compact view over PQ schemes (all rows if no PQ present):")
    w()
    sub = score[score.family == "pq"] if pq_present else score
    rows1 = []
    for (gname, m), g in sub.groupby(["group", "mode"]):
        r = {"group": gname, "mode": m}
        for pn, gg in g.groupby("profile"):
            r[pn] = f"{int(gg.fits.sum())}/{len(gg)}"
        rows1.append(r)
    w("Cells are fitting schemes / schemes in the family."); w(); w(md(pd.DataFrame(rows1))); w()
    if pq_present:
        w("Schemes whose full signature fits each profile (`fits` in `raw/scoring.csv`):"); w()
        for pn, g in sub[(sub["mode"] == "full") & (sub.group != "SLH-DSA")].groupby("profile"):
            w(f"- {pn} (SLH-DSA: " + str(int(sub[(sub['mode'] == 'full') & (sub.group == 'SLH-DSA') & (sub.profile == pn)].fits.sum())) + " parameter sets fit): " + (", ".join(g[g.fits].scheme) or "none"))
        w()
    fig, ax = plt.subplots(figsize=(9, 4))
    modes = list(sub["mode"].unique())
    for i, m in enumerate(modes):
        g = sub[sub["mode"] == m]
        xs = [list(prof["profiles"]).index(p) + (i - 2) * 0.12 for p in g.profile]
        ax.scatter(xs, g.share_of_budget, s=6, label=m)
    ax.set_xticks(range(len(prof["profiles"]))); ax.set_xticklabels(list(prof["profiles"]))
    ax.axhline(1, color="k", ls="--"); ax.set_yscale("log"); ax.set_ylabel("auth bytes / budget (one dot per scheme)")
    ax.legend(fontsize=7); fig.tight_layout(); fig.savefig(os.path.join(RES, "fig_q1_share.pdf")); plt.close(fig)
    w("Figure: `fig_q1_share.pdf` (source `raw/scoring.csv`).")
w()
if pq_present:
    full = sub[sub["mode"] == "full"]; ch = sub[sub["mode"] == "chain"]
    w(f"**Verdict Q1: answered by the tables (supported as a descriptive question). Full signature fits in {int(full.fits.sum())}/{len(full)} (scheme, profile) pairs; "
      f"the PQ-anchored chain fits in {int(ch.fits.sum())}/{len(ch)}; sig+cert fits in {int(sub[sub['mode']=='sig_cert'].fits.sum())}/{len(full)}. "
      "Fragmented 'fits' means total bytes only; see frames column for the multi-frame cost.**")
else:
    w("**Verdict Q1: inconclusive (pending). Only classical rows can be scored.**")
w()

# ---- Q2
w("## Q2: PQ-anchored chain vs fragmented signatures at 0-30% loss")
w()
w("Source: `results/raw/lossmodel.csv`. Seeded i.i.d. loss; 20 seeds x 5000 messages per cell; mean and std across seeds.")
w("Parameters: k=13 (FN-DSA) / 34 (ML-DSA) fragments, 324 B anchor (darzi2026a); signature 666 B / 2420 B (junquera2023assessment, Falcon-512 / Dilithium2 as in that note; "
  "cited; scenarios cited13/cited34; scenarios oqs13/oqs34 use the liboqs-measured sig_bytes_max of Falcon-512 / ML-DSA-44 and an anchor of measured MAYO-1 signature + 16 + 4 B, with k still taken from darzi2026a, not recomputed). Assumed, not cited: r=2 carousel cycles, key delay d=2 slots, epoch 20 slots, 2 anchors/epoch, 16 B disclosed key, slot 160 ms (SIB1 period), deadline = r*k slots. "
  "Model: see `lib/pqsig/lossmodel.py` docstring. Results are sensitive to these assumptions.")
w()
verd = {}
if loss is not None:
    g = loss.groupby(["scenario", "scheme", "loss"])
    m = g[["share_verified", "bytes_per_verified", "p95_ms"]].agg(["mean", "std"])
    m.columns = ["_".join(c) for c in m.columns]
    m = m.reset_index()
    w(md(m)); w()
    fig, axs = plt.subplots(1, 3, figsize=(12, 3.5))
    for (scen, sch), gg in m.groupby(["scenario", "scheme"]):
        for ax, col in zip(axs, ("share_verified", "bytes_per_verified", "p95_ms")):
            ax.errorbar(gg.loss, gg[col + "_mean"], yerr=gg[col + "_std"], label=f"{scen}/{sch}", marker="o", ms=3, capsize=2)
            ax.set_xlabel("loss"); ax.set_ylabel(col)
    axs[1].set_yscale("log"); axs[0].legend(fontsize=6); fig.tight_layout()
    fig.savefig(os.path.join(RES, "fig_q2_loss.pdf")); plt.close(fig)
    w("Figure: `fig_q2_loss.pdf` (source `raw/lossmodel.csv`).")
    w()
    # per-metric verdicts: chain better at every loss>0 in every scenario with gap > 2 pooled std
    for col, better in (("share_verified", "higher"), ("bytes_per_verified", "lower"), ("p95_ms", "lower")):
        wins, tot = 0, 0
        for scen in m.scenario.unique():
            for lo in sorted(m.loss.unique()):
                if lo == 0: continue
                c = m[(m.scenario == scen) & (m.scheme == "chain") & (m.loss == lo)].iloc[0]
                f = m[(m.scenario == scen) & (m.scheme == "fragmented") & (m.loss == lo)].iloc[0]
                d = c[col + "_mean"] - f[col + "_mean"]
                if better == "lower": d = -d
                tot += 1; wins += d > 2 * max(c[col + "_std"], f[col + "_std"], 1e-12)
        verd[col] = (wins, tot)
    w("Cells where chain is better by more than 2 std (loss > 0, both scenarios):")
    w(); w(md(pd.DataFrame([{"metric": k, "chain_better_cells": a, "cells": b} for k, (a, b) in verd.items()]))); w()
    allw = all(a == b for a, b in verd.values()); none = all(a == 0 for a, b in verd.values())
    cnt = "; ".join(f"{k}: {a}/{b}" for k, (a, b) in verd.items())
    w("**Verdict Q2: " + ("supported" if allw else "refuted" if none else
      "inconclusive (mixed) under these smoke assumptions (" + cnt + " cells where chain is better by >2 std); chain is not better on every metric at every loss level") +
      ". Counts span cited and liboqs-size scenarios.** p95 time is taken over verified messages only and is capped by the deadline, so a low verified share flatters the fragmented p95. "
      "The darzi2026a 10% point (~41 B vs ~1971 B retransmission overhead) uses a retransmission accounting that this carousel model does not reproduce; TODO-RESULT.")
w()

sweep = load("lossmodel_sweep.csv")
if sweep is not None:
    w("### Q2 parameter sweep")
    w()
    w("Source: `results/raw/lossmodel_sweep.csv` (one-at-a-time r, d, E, a around the baseline; loss 5/10/30%; chain-vs-fragmented compared per scenario/sweep value/loss over seeds).")
    w()
    g = sweep.groupby(["scenario", "scheme", "sweep_var", "sweep_val", "loss"])[["share_verified", "bytes_per_verified", "p95_ms"]].mean().reset_index()
    ch = g[g.scheme == "chain"].set_index(["scenario", "sweep_var", "sweep_val", "loss"]); fr = g[g.scheme == "fragmented"].set_index(["scenario", "sweep_var", "sweep_val", "loss"])
    cmp_ = pd.DataFrame({"chain_better_share": ch.share_verified > fr.share_verified, "chain_better_bytes": ch.bytes_per_verified < fr.bytes_per_verified,
                         "chain_better_p95": ch.p95_ms < fr.p95_ms}).reset_index()
    t = cmp_.groupby(["scenario", "sweep_var"])[["chain_better_share", "chain_better_bytes", "chain_better_p95"]].agg(["sum", "count"]).reset_index()
    t.columns = ["_".join(c).strip("_") for c in t.columns]
    w(md(t)); w()
    w("Sweep cells: " + str(len(cmp_)) + "; chain better on share/bytes/p95 in " + ", ".join(str(int(cmp_[c].sum())) for c in ("chain_better_share", "chain_better_bytes", "chain_better_p95")) + " cells respectively.")
    w()

# ---- Q3
w("## Q3: size or timing tail binding (deadline miss from sign/verify tails)")
w()
w("Source: `results/raw/*timing*.csv` columns `*_frac_gt3ms`, `*_frac_gt100ms` (fraction of iterations over 3 ms / 100 ms), x86 only; MCU figures are cited from chhetri2026benchmarking, not measured.")
w()
if pq_present:
    t3 = timing[timing.family == "pq"].copy()
    big = t3.iterations >= 1000
    t3["tail_us"] = t3[["sign_p99_us", "verify_p99_us"]].max(axis=1).where(big, t3[["sign_median_us", "verify_median_us"]].max(axis=1))
    t3["tail_basis"] = big.map({True: "p99", False: "median (n<100, tail not estimable)"})
    full = score[(score["mode"] == "full") & (score.family == "pq")]
    rows3 = []
    for gname, g in t3.groupby("group"):
        fg = full[full.group == gname]
        r = {"group": gname, "schemes": len(g), "tail_basis": "/".join(sorted(g.tail_basis.unique())),
             "full_sig_misfit_frac": float((~fg.fits).mean())}
        for dn, dv in prof["deadlines_ms"].items():
            r[f"over_{dv['value']}ms_frac"] = float((g.tail_us > dv["value"] * 1000).mean())
        rows3.append(r)
    r3 = pd.DataFrame(rows3)
    w("Per family: fraction of (scheme, profile) pairs where the full signature does not fit, vs fraction of schemes whose sign or verify tail exceeds the deadline (x86 liboqs; p99 where n >= 1000, median otherwise). Per-iteration fractions over each deadline are the `*_frac_gt*` columns in the timing CSV.")
    w(); w(md(r3)); w()
    c3, c100 = [c for c in r3.columns if c.startswith("over_")]
    bound = {"size": int(((r3.full_sig_misfit_frac > r3[c3]) & (r3.full_sig_misfit_frac > r3[c100])).sum()),
             "timing": int(((r3.full_sig_misfit_frac < r3[c3]) & (r3.full_sig_misfit_frac < r3[c100])).sum())}
    fig, ax = plt.subplots(figsize=(8, 3.5)); x = range(len(r3))
    ax.bar([i - .27 for i in x], r3.full_sig_misfit_frac, .27, label="size misfit")
    ax.bar(list(x), r3[c3], .27, label="over 3 ms"); ax.bar([i + .27 for i in x], r3[c100], .27, label="over 100 ms")
    ax.set_xticks(list(x)); ax.set_xticklabels(r3.group, rotation=30, fontsize=7); ax.legend(fontsize=7); fig.tight_layout()
    fig.savefig(os.path.join(RES, "fig_q3_size_vs_tail.pdf")); plt.close(fig)
    w("Figure: `fig_q3_size_vs_tail.pdf` (source `raw/*timing*.csv`, `raw/scoring.csv`).")
    w()
    verdict = "size binding (supported; no family is timing-bound, ties count as not distinguishing)" if bound["timing"] == 0 and bound["size"] > 0 else "timing tail binding (size-binding refuted)" if bound["timing"] == len(r3) else "inconclusive (differs by family)"
    w(f"**Verdict Q3: {verdict}. Size is the larger bound in {bound['size']}/{len(r3)} families and timing in {bound['timing']}/{len(r3)} (both deadlines). x86 only; MCU timing not measured, so this does not cover constrained devices. Tails are from <= 1000 iterations on a shared cloud VM.**")
else:
    w("**Verdict Q3: inconclusive (pending).**")
w()
w("## Runs still needed (on the user's machines, `experiments/run.sh`)")
w()
w("- Part A on every target machine: `MACHINE_NAME=<name> ITER=10000 ITER_SLOW=200 ./run.sh` (cloud-smoke used 1000 iterations, and 20 for SLH-DSA/CROSS/MQOM, so their tails are not estimable). Stateful LMS/XMSS are not benchmarked (stateful API, not in oqs_bench.c).")
w("- Part B re-score on those sizes (`score.py` is run by `run.sh`); includes MAYO/UOV/SNOVA/CROSS if the liboqs build enables them (enabled by the cmake flags in `run.sh`; liboqs 0.16.0 builds all of them).")
w("- Part C (liboqs sizes and sweep done on cloud-smoke); re-run via run.sh on target machines. Still open: k recomputed from the actual fragment payload of each profile; correlated (burst) loss; darzi2026a retransmission accounting.")
w("- Baselines pending: darzi2026a 34/13 fragments and 324 B; junquera2023assessment 67/71 blocks (full text check); chen2025hybrid size tables vs liboqs; yoshizawa2026a (Bulletproofs); goertzen2022post.")
open(os.path.join(RES, "summary.md"), "w").write("\n".join(L) + "\n")
