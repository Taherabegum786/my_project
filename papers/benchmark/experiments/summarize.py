def paired(m1, m2, metric, favour, mineff, aggfun=None):
    a = res[res["mode"] == m1][["profile", "pq", "M", "loss_model", "loss_p", "burst_len", "seed", metric, "feasible"]]
    b = res[res["mode"] == m2][["profile", "pq", "M", "loss_model", "loss_p", "burst_len", "seed", metric, "feasible"]]
    j = a.merge(b, on=["profile", "pq", "M", "loss_model", "loss_p", "burst_len", "seed"], suffixes=("_a", "_b"))
    j = j[j.loss_p > 0]
    out = []
    for k, g in j.groupby(["profile", "pq", "M", "loss_model", "loss_p", "burst_len"]):
        x = pd.to_numeric(g[metric + "_a"], errors="coerce"); y = pd.to_numeric(g[metric + "_b"], errors="coerce")
        if metric != "share" and (x.isna().any() or y.isna().any()):
            continue
        d = (x - y).dropna()
        if len(d) < 2:
            continue
        se = d.std(ddof=1) / np.sqrt(len(d)); mean = d.mean(); ref = max(abs(y.mean()), 1e-12)
        eff = abs(mean) if metric == "share" else abs(mean) / ref
        decisive = eff > mineff and (abs(mean) > 3 * se if se > 0 else abs(mean) > 0)
        fav = (mean > 0) if favour == "higher" else (mean < 0)
        out.append(dict(frag_feasible=int(g["feasible_b"].iloc[0]), profile=k[0], pq=k[1], M=k[2], cond=("iid %g" % k[4]) if k[3] == "iid" else "GE %g/b%d" % (k[4], k[5]), diff=mean, se=se,
                        outcome="win" if decisive and fav else "loss" if decisive else "tie"))
    return pd.DataFrame(out)


def verdict(df):
    wn, ls = int((df.outcome == "win").sum()), int((df.outcome == "loss").sum())
    v = "supported" if wn >= 2 * ls and wn > 0 else "refuted" if ls >= 2 * wn and ls > 0 else "inconclusive"
    return wn, ls, int((df.outcome == "tie").sum()), v


