def rd(name):
    return pd.read_csv(os.path.join(IN, name))


def tci(x):
    x = np.asarray(x, float)
    x = x[~np.isnan(x)]
    n = len(x)
    if n < 2:
        return (x.mean() if n else np.nan), np.nan, np.nan
    h = stats.t.ppf(0.975, n - 1) * x.std(ddof=1) / np.sqrt(n)
    return x.mean(), x.mean() - h, x.mean() + h


def agg(d, keys, metrics):
    rows = []
    for k, g in d.groupby(keys, sort=False):
        r = dict(zip(keys, k if isinstance(k, tuple) else (k,)))
        r["reps"] = len(g)
        for m in metrics:
            mm, lo, hi = tci(pd.to_numeric(g[m], errors="coerce"))
            r[m] = mm
            r[m + "_lo"] = lo
            r[m + "_hi"] = hi
        rows.append(r)
    return pd.DataFrame(rows)


def tex(path, header, rows, caption, label, colspec=None):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    colspec = colspec or ("l" * len(header))
    with open(path, "w") as f:
        f.write("%% generated by plots/make_r1.py -- do not edit\n")
        f.write("\\begin{table*}[t]\n\\centering\\scriptsize\n\\caption{%s}\\label{%s}\n" % (caption, label))
        f.write("\\begin{tabular}{%s}\n\\toprule\n" % colspec)
        f.write(" & ".join(header) + " \\\\\n\\midrule\n")
        for r in rows:
            f.write(" & ".join(str(x) for x in r) + " \\\\\n")
        f.write("\\bottomrule\n\\end{tabular}\n\\end{table*}\n")
    say("wrote", os.path.relpath(path, IN))


def fmt(x, nd=3):
    if x is None or (isinstance(x, float) and np.isnan(x)):
        return "--"
    if abs(x) >= 1000:
        return "{:,.0f}".format(x)
    return ("%." + str(nd) + "g") % x


