# ======================================================================= B11 delegation trade-off (M9, item 8)
def b11(a_oprg):
    """Analytic, from measured costs: exposure window of a delegated Ed25519 key = L (delegation lifetime) + V_max
    (acceptance of tokens signed under it). B11 is quantum-safe for a key only if an adversary's time-to-break
    t_break > L + V_max.  Cost of shrinking L: per-edge certificate fetches and ML-DSA verifications ~ T_active/L,
    fleet certificate bytes (E + S) * T_active * cert_B / L (the same formula as sim_dissem.csv's B11 rows)."""
    nat = rd("native_sig_agg.csv").set_index(["scheme", "op"]).median_us
    t_ml_v, t_ml_s = nat[("ML-DSA-44", "verify")], nat[("ML-DSA-44", "sign")]
    t_ed_s, t_ed_v = nat[("ED25519", "sign")], nat[("ED25519", "verify")]
    E, S, T, Vmax = 500, 50, 1000, 3600.0
    cert_B = 48 + 2420 + 40
    rows = []
    for L in (10.0, 60.0, 300.0, 900.0, 3600.0, 6 * 3600.0, 86400.0):
        per_edge_cert_s = T / L
        rows.append(dict(L_s=L, exposure_window_s=L + Vmax, exposure_window_if_Vmax_600s=L + 600.0,
                         cert_fetches_per_edge_per_s=per_edge_cert_s,
                         edge_cert_verify_cpu_frac=per_edge_cert_s * t_ml_v * 1e-6,
                         fleet_cert_Bps=(E + S) * T * cert_B / L, issuer_cert_sign_cores=T / L * t_ml_s * 1e-6,
                         b11_issuer_us_per_token=t_ed_s, b11_edge_verify_us_per_token_edge=t_ed_v))
    o = pd.DataFrame(rows)
    o.to_csv(os.path.join(IN, "r1_b11_tradeoff.csv"), index=False)
    say("\n=== B11 DELEGATION TRADE-OFF (analytic from native run-2 costs; T=%d tenants, E=%d, S=%d, V_max=%g s) ===" % (T, E, S, Vmax))
    say("native: ML-DSA-44 sign %.1f verify %.1f us; Ed25519 sign %.1f verify %.1f us; cert %d B" % (t_ml_s, t_ml_v, t_ed_s, t_ed_v, cert_B))
    for x in o.itertuples():
        say("L=%7.0f s window(L+Vmax)=%7.0f s (L+600 s: %6.0f) cert fetch/edge/s=%.3f edge CPU=%.5f core fleet cert BW=%.3g B/s issuer cert sign=%.5f cores" % (
            x.L_s, x.exposure_window_s, x.exposure_window_if_Vmax_600s, x.cert_fetches_per_edge_per_s,
            x.edge_cert_verify_cpu_frac, x.fleet_cert_Bps, x.issuer_cert_sign_cores))
    # per-token comparison at lam=2000 from oprg (EMBER pooled) vs B11
    if a_oprg is not None:
        for lam in (2000, 20000):
            for pool, pol in (("tenant", "pertoken"), ("tenant", "fixed:0.01"), ("global", "fixed:0.01"), ("global", "wc")):
                r = a_oprg[(a_oprg.lambda_bar == lam) & (a_oprg.pooling == pool) & (a_oprg.policy == pol) & (a_oprg["mode"] == "pull_staple")]
                if len(r):
                    r = r.iloc[0]
                    say("lam=%g %s %s: issuer %.2f us/token (%.4f cores); B11 issuer %.1f us/token (%.4f cores); "
                        "edge sig verifs/edge/s %.3f (B11 with verify cache ~ sessions/edge/s = same as M2)" % (
                            lam, pool, pol, r.issuer_cpu_us_per_token, r.issuer_cpu_cores, t_ed_s, lam * t_ed_s * 1e-6,
                            r.sig_verifs_per_edge_per_s))
    setup()
    fig, ax = plt.subplots(figsize=(COL, 2.3))
    tb = np.logspace(np.log10(60), np.log10(30 * 86400), 200)
    for k, (V, lab) in enumerate(((3600.0, "$V_{max}$=1 h"), (600.0, "$V_{max}$=10 min"))):
        Lmax = np.maximum(tb - V, np.nan)
        Lmax[tb <= V] = np.nan
        ax.plot(tb / 3600, Lmax / 60, ls=LINES[k], color=SERIES[k], lw=1.3, label="longest safe $L$, " + lab)
        ax.axvline(V / 3600, color=SERIES[k], lw=0.7, ls=":")
    ax.set_xscale("log"); ax.set_yscale("log")
    ax.set_xlabel("adversary time to break one Ed25519 key, $t_{break}$ (h)")
    ax.set_ylabel("max. delegation lifetime $L$ (min)")
    ax2 = ax.twinx()
    Ls = np.logspace(np.log10(10), np.log10(86400), 50)
    ax2.plot((Ls + 3600) / 3600, (E + S) * T * cert_B / Ls / 1e6, color=SERIES[2], ls=LINES[2], lw=1,
             label="fleet cert. bytes at that $L$ ($V_{max}$=1 h)")
    ax2.set_yscale("log")
    ax2.set_ylabel("B11 fleet cert. MB/s", color=SERIES[2])
    ax2.grid(False)
    ax2.spines["right"].set_visible(True)
    h1, l1 = ax.get_legend_handles_labels()
    h2, l2 = ax2.get_legend_handles_labels()
    ax.legend(h1 + h2, l1 + l2, fontsize=6, loc="upper left")
    ax.text(0.3, 0.05, "left of dotted line: B11 unsafe for\nevery $L$; EMBER/M2 preferable", transform=ax.transAxes,
            fontsize=6, color=INK2)
    save(fig, os.path.join(IN, "figures"), "fig15_b11_tradeoff")


