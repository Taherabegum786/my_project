def tab6():
    ts = rd("token_sizes.csv")
    ts = ts[(ts.url_path_len == 60) & (ts.with_ip == 0)]
    ns = rd("native_sig_agg.csv")
    pv = rd("native_pathverify_agg.csv")

    def tb(s, lg=None):
        r = ts[ts.scheme == s] if lg is None else ts[(ts.scheme == s) & (ts.log2N == lg)]
        return int(r.token_bytes.iloc[0]) if len(r) else None

    def nv(s):
        return ns[(ns.scheme == s) & (ns.op == "verify")].median_us.iloc[0]

    hm = pv[(pv.impl == "evp") & (pv.op == "hmac_sha256_200B")].ns_median.iloc[0] / 1e3
    p16 = pv[(pv.impl == "evp") & (pv.op == "pathverify") & (pv.d == 16) & (pv.n == 16)].ns_median.iloc[0] / 1e3
    sh = pv[(pv.impl == "evp") & (pv.op == "sha256_3500B")]
    sh = sh.ns_median.iloc[0] / 1e3 if len(sh) else np.nan
    dis = {}
    try:
        d = rd("sim_dissem.csv")
        d = d[(d.E == 500) & (d.delta_s.astype(float).isin([1.0, 3600.0]))]
        for (s, m), g in d.groupby(["scheme", "mode"]):
            dis[(s, m)] = g.root_bw_fleet_Bps.astype(float).mean()
    except FileNotFoundError:
        pass

    def bw(k):
        return fmt(dis[k] / 1e3, 1) if k in dis else "--"
    rows = [
        ("B1 HMAC", "yes (key lifetime)", "all edges, all paths of the key", "unconditional", "no", tb("B1"), fmt(hm, 2), "0"),
        ("B10 multi-MAC k=3", "yes", "its own domain", "unconditional", "no", tb("B10k3"), fmt(hm, 2), "0"),
        ("B12 KEM-wrapped HMAC", "yes (epoch keys)", "all edges, live epochs", "unconditional (ML-KEM)", "no", tb("B12"), fmt(hm, 2),
         bw(("B12", "push"))),
        ("B2 Ed25519", "no", "none", "none (Shor)", "yes", tb("B2"), fmt(nv("ED25519")), "0"),
        ("B11 deleg. Ed25519", "no", "none", "classical within $V_{max}$", "yes", tb("B11"), fmt(nv("ED25519")), bw(("B11", "pull"))),
        ("B5 ML-DSA-44", "no", "none", "unconditional", "yes", tb("B5"), fmt(nv("ML-DSA-44")), "0"),
        ("B5v + vcache", "no", "none", "unconditional", "yes", tb("B5"),
         "%s first, %s hit" % (fmt(nv("ML-DSA-44")), fmt(sh, 2)), "0"),
        ("EMBER O1 (pull)", "no", "none", "unconditional", "yes", tb("O1", 16), fmt(p16, 2) + " (+root/epoch)",
         bw(("EMBER-O1", "pull"))),
        ("EMBER O1 (push)", "no", "none", "unconditional", "yes", tb("O1", 16), fmt(p16, 2), bw(("EMBER-O1", "push")))]
    body = ("\\begin{table*}[t]\\centering\\caption{Trust and cost comparison. Token bytes: 60-char path, no IP "
            "(measured; EMBER at $N=2^{16}$). Verify: native OpenSSL 3.5.4 median $\\mu$s per request (EMBER: path "
            "$d$=16). Dissemination: simulated fleet root/key/cert bytes/s, $E$=500, $\\bar\\lambda$=2000/s, "
            "$\\Delta$=1 s, kB/s.}\\label{tab:trust}\\small\n"
            "\\begin{tabular}{llllrrll}\\toprule\nScheme & secret at edge & one edge compromised mints for & PQ assumption & "
            "account. & bytes & verify ($\\mu$s) & dissem. (kB/s) \\\\\\midrule\n"
            + "\n".join("%s & %s & %s & %s & %s & %s & %s & %s \\\\" % r for r in rows)
            + "\n\\bottomrule\\end{tabular}\\end{table*}\n")
    w("tab6_trust", body)


