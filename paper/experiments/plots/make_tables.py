def controller_stats():
    d = rd("sim_controller_summary.csv")
    out = []
    for lam, g in d.groupby("lambda_bar"):
        ad = g[g.policy == "adaptive"].set_index("rep").D_mean_s
        for pol, h in g.groupby("policy", sort=False):
            m, lo, hi = tci(h.D_mean_s)
            row = dict(lambda_bar=lam, policy=pol, reps=len(h), D=m, D_lo=lo, D_hi=hi,
                       slo=pd.to_numeric(h.slo_violation_frac, errors="coerce").mean(),
                       bud=pd.to_numeric(h.budget_violation_frac, errors="coerce").mean(),
                       p99=pd.to_numeric(h.issue_wait_p99_s, errors="coerce").mean(),
                       choice=";".join(sorted(set(str(x) for x in h.oracle_choice.fillna("") if str(x) not in ("", "nan")))))
            if pol != "adaptive":
                o = h.set_index("rep").D_mean_s
                diff = (ad - o).dropna()
                dm, dlo, dhi = tci(diff.values)
                row.update(diff=dm, diff_lo=dlo, diff_hi=dhi, rel=dm / o.mean())
            out.append(row)
    return pd.DataFrame(out)


